JOINT_INFO = {}


def _get_joint_info(robot_name):
    validate_hand_name(robot_name)
    if robot_name not in JOINT_INFO:
        from utils.handmodel import get_handmodel

        hand = get_handmodel(1, "cpu", robot_name, 1.0, None)
        JOINT_INFO[robot_name] = hand.initialize_joint_info()
    return JOINT_INFO[robot_name]

def joint_to_unified_dim(joint_angle_norm: torch.Tensor, robot_name: str, masked_fingers: list = None):
    if robot_name not in ROBOT_JOINT_MAPPINGS:
        raise ValueError(f"Unsupported robot: {robot_name}")

    mapping_info = ROBOT_JOINT_MAPPINGS[robot_name]

    input_shape = joint_angle_norm.shape
    last_dim = input_shape[-1]
    expected_dim = mapping_info["original_joint_dim"]

    if last_dim != expected_dim:
        raise ValueError(f"Expected last dimension to be {expected_dim} for {robot_name}, got {last_dim}")

    output_shape = input_shape[:-1] + (24,)

    unified_joint = torch.zeros(output_shape, device=joint_angle_norm.device, dtype=joint_angle_norm.dtype)
    padding_mask = torch.zeros(output_shape, device=joint_angle_norm.device, dtype=torch.float32)

    for orig_idx, unified_idx in mapping_info["joint_to_unified"].items():
        unified_joint[..., unified_idx] = joint_angle_norm[..., orig_idx]
        padding_mask[..., unified_idx] = 1.0

    if masked_fingers:
        for finger in masked_fingers:
            if finger in UNIFIED_FINGER_RANGES:
                for idx in UNIFIED_FINGER_RANGES[finger]:
                    unified_joint[..., idx] = 0.0
                    padding_mask[..., idx] = 0.0

    return unified_joint, padding_mask


def unified_to_joint_dim(unified_joint: torch.Tensor, robot_name: str, masked_fingers: list = None):
    if robot_name not in ROBOT_JOINT_MAPPINGS:
        raise ValueError(f"Unsupported robot: {robot_name}")

    mapping_info = ROBOT_JOINT_MAPPINGS[robot_name]

    input_shape = unified_joint.shape
    last_dim = input_shape[-1]

    if last_dim != 24:
        raise ValueError(f"Expected last dimension to be 24, got {last_dim}")

    original_joint_dim = mapping_info["original_joint_dim"]
    output_shape = input_shape[:-1] + (original_joint_dim,)

    joint_angle = torch.zeros(output_shape, device=unified_joint.device, dtype=unified_joint.dtype)

    for unified_idx, orig_idx in mapping_info["unified_to_joint"].items():
        is_masked = False
        if masked_fingers:
            for finger in masked_fingers:
                if finger in ROBOT_FINGER_RANGES[robot_name] and orig_idx in ROBOT_FINGER_RANGES[robot_name][finger]:
                    is_masked = True
                    break

        if not is_masked:
            joint_angle[..., orig_idx] = unified_joint[..., unified_idx]

    return joint_angle


def matrix_to_unified_dim(matrix: torch.Tensor, robot_name: str, masked_fingers=None):
    if robot_name not in ROBOT_JOINT_MAPPINGS:
        raise ValueError(f"Unsupported robot: {robot_name}")

    mapping_info = ROBOT_JOINT_MAPPINGS[robot_name]

    input_shape = matrix.shape
    expected_dim = mapping_info["original_joint_dim"]

    if len(input_shape) == 2:
        # [original_dim, original_dim]
        if input_shape[0] != expected_dim or input_shape[1] != expected_dim:
            raise ValueError(f"Expected shape [{expected_dim}, {expected_dim}] for {robot_name}, got {input_shape}")
        batch_shape = ()
        output_shape = (27, 27)
    elif len(input_shape) == 3:
        # [B, original_dim, original_dim]
        if input_shape[1] != expected_dim or input_shape[2] != expected_dim:
            raise ValueError(f"Expected shape [*, {expected_dim}, {expected_dim}] for {robot_name}, got {input_shape}")
        batch_shape = input_shape[:-2]
        output_shape = batch_shape + (27, 27)
    else:
        raise ValueError(f"Unsupported input shape: {input_shape}")

    unified_matrix = torch.zeros(output_shape, device=matrix.device, dtype=matrix.dtype)
    mask = torch.zeros(output_shape, device=matrix.device, dtype=torch.float32)

    for orig_i, unified_i in mapping_info["joint_to_unified"].items():
        for orig_j, unified_j in mapping_info["joint_to_unified"].items():
            is_i_masked = False
            is_j_masked = False
            if masked_fingers:
                for finger in masked_fingers:
                    if finger in ROBOT_FINGER_RANGES[robot_name]:
                        if orig_i in ROBOT_FINGER_RANGES[robot_name][finger]:
                            is_i_masked = True
                        if orig_j in ROBOT_FINGER_RANGES[robot_name][finger]:
                            is_j_masked = True

            if not is_i_masked and not is_j_masked:
                final_i = unified_i + 3
                final_j = unified_j + 3

                if len(input_shape) == 2:
                    unified_matrix[final_i, final_j] = matrix[orig_i, orig_j]
                else:
                    unified_matrix[..., final_i, final_j] = matrix[..., orig_i, orig_j]

                mask[..., final_i, final_j] = 1.0

    return unified_matrix, mask

